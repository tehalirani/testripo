def vocal_map(name):
    d = np.load(os.path.join(WORK, f'dtw_vocal_{name}.npy'))
    st, lt = d[:, 0], d[:, 1]
    grid = np.arange(st.min(), st.max(), 0.05)
    m = np.interp(grid, st, lt)
    k = 20
    m = np.convolve(np.pad(m, k, mode='edge'), np.ones(2 * k + 1) / (2 * k + 1), 'valid')
    m = np.maximum.accumulate(m)
    return lambda t: np.interp(t, grid, m)


def women_layer_dry(seed=20):
    """مثل V20.women_layer، با ریورب کم و وسط استریوی خالی‌تر."""
    from make_live import pan, to_sides
    r = np.random.default_rng(seed)
    ref = M.voc[:, int(V10.SRC_T0 * SR):int((V10.SRC_T0 + 41) * SR)].mean(0)
    tracks = []
    for f in V20.WOMEN:
        y = V10.load_voice(os.path.join(REC, f)); lag = V10.align(y, ref)
        y = y[int(max(lag, 0) * SR):]
        full = np.zeros(N, np.float32); a = int(V10.SRC_T0 * SR); full[a:a + len(y)] = y[:N - a]
        full *= env(N, [(V20.CH1[0] - 0.3, V20.CH1[1] + 0.5, 0, 0.3, 0.6)])
        tracks.append(full)
    g2, m2 = V20.map_sections(V20.CH1, V20.CH2)
    g3, m3 = V20.map_sections((V20.CH1[0], V20.CH1[0] + (V20.CH3[1] - V20.CH3[0]) + 1.0), V20.CH3)
    out = np.zeros((2, N), np.float32); parts = {}
    for name, rng in [('ch1', V20.CH1), ('ch2', V20.CH2)]:          # کُرس آخر بدون زنان (نسخه ۲۵)
        layer = np.zeros((2, N), np.float32)
        for i, tr in enumerate(tracks):
            z = tr if name == 'ch1' else V20.warp_track(tr, *((g2, m2) if name == 'ch2' else (g3, m3)))
            layer += pan(z, [-0.8, 0.85, -0.5][i] + r.uniform(-0.1, 0.1)) * r.uniform(0.8, 1.0)
        layer = Pedalboard([HighpassFilter(180), LowpassFilter(3500), PeakFilter(3000, -3.0, 0.9),
                            Compressor(threshold_db=-30, ratio=2.5, attack_ms=20, release_ms=200),
                            Reverb(room_size=0.6, damping=0.7, wet_level=0.15, dry_level=0.9, width=1.0)])(layer, SR)
        layer = to_sides(layer, mid_db=-10.0) * env(N, [(rng[0] - 0.3, rng[1] + 1.0, 0, 0.6, 1.0)])
        sl = slice(int(rng[0] * SR), int(rng[1] * SR))
        boost = {'ch1': 2.0, 'ch2': 2.5, 'ch3': 1.5}[name]
        layer *= db(V20.WOMEN_DB[name] - 8.0) * rms(M.voc[:, sl] * db(boost)) / rms(layer[:, sl])
        out += layer; parts[name] = V20.WOMEN_DB[name] - 8.0
    return out, parts


